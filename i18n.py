"""Presentation-only translations; workbook inputs and calculation keys stay stable.

Language is scoped to the current execution context, so concurrent Streamlit
sessions do not share their language choice. Product names, machine identifiers,
codes, numeric values and the source Excel template names are never translated.
"""

