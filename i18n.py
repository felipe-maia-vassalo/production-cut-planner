_language = ContextVar("production_cut_planner_language", default="pt")


def set_language(language):
    """Select ``pt`` or ``en`` for the current session execution context."""
    if language not in ("pt", "en"):
        raise ValueError("Language must be 'pt' or 'en'.")
    return _language.set(language)


def tr(portuguese, english):
    return english if _language.get() == "en" else portuguese


