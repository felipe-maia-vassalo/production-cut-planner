def localized_error(error):
    """Translate application validation errors while preserving source references."""
    message = str(error)
    if _language.get() != "en":
        return message
    if message in _ERROR_EXACT:
        return _ERROR_EXACT[message]
    for pattern, replacement in _ERROR_PATTERNS:
        if re.fullmatch(pattern, message, flags=re.DOTALL):
            translated = re.sub(pattern, replacement, message, flags=re.DOTALL)
            # These are engine-defined field descriptions, not user text.
            translated = re.sub(r"^Quantidade do produto (.+?)(?= is empty\.| must be|:)", r"Quantity for product \1", translated)
            translated = re.sub(r"^QUANT na linha (\d+)", r"QUANT at row \1", translated)
            translated = re.sub(r"^Quantidade(?= is empty\.| must be|:)", "Quantity", translated)
            translated = re.sub(r"^Invalid Quantidade do produto (.+?):", r"Invalid quantity for product \1:", translated)
            translated = re.sub(r"^Invalid QUANT na linha (\d+):", r"Invalid QUANT at row \1:", translated)
            translated = re.sub(r"^Invalid Quantidade:", "Invalid quantity:", translated)
            return re.sub(r"\bTurno (\d+)\b", r"Shift \1", translated)
    # Third-party exceptions (for example corrupt workbooks) already use English.
    return message
