# Only these fields contain text generated by the application. Free-text source
# columns such as descriptions and tube specifications must remain untouched.
_OWNED_TEXT_COLUMNS = {
    "CÓDIGO", "MÉTODO", "STATUS", "TURNO", "PARTICIPA", "PAUSA",
    "PAUSA ALMOÇO", "REGRA", "MOTIVO", "FAMÍLIA",
}


def _translate_owned_value(value, reverse=False):
    if not isinstance(value, str):
        return value
    labels = {v: k for k, v in _VALUE_LABELS.items()} if reverse else _VALUE_LABELS
    if value in labels:
        return labels[value]
    if reverse:
        if value.startswith("Possible codes: "):
            return "Possíveis códigos: " + value[len("Possible codes: "):]
        return re.sub(r"\bShift (\d+)\b", r"Turno \1", value)
    if value.startswith("Possíveis códigos: "):
        return "Possible codes: " + value[len("Possíveis códigos: "):]
    return re.sub(r"\bTurno (\d+)\b", r"Shift \1", value)


def _transform_owned_columns(frame, reverse=False):
    for name in _OWNED_TEXT_COLUMNS.intersection(frame.columns):
        frame[name] = frame[name].map(lambda value: _translate_owned_value(value, reverse))
    # The matched-product field otherwise contains unmodified workbook data.
    if "PRODUTO ENCONTRADO" in frame.columns and "CÓDIGO" in frame.columns:
        markers = ("Verificar", "Não encontrado")
        if reverse:
            markers += ("Check", "Not found")
        missing = frame["CÓDIGO"].isin(markers if reverse else ("Check", "Not found"))
        frame.loc[missing, "PRODUTO ENCONTRADO"] = frame.loc[missing, "PRODUTO ENCONTRADO"].map(
            lambda value: _translate_owned_value(value, reverse)
        )
    return frame


def localized_frame(dataframe):
    """Return a localized presentation copy without changing engine data."""
    frame = dataframe.copy(deep=True)
    if _language.get() == "en":
        _transform_owned_columns(frame)
        frame = frame.rename(columns=COLUMN_LABELS)
    return frame


def source_frame(dataframe):
    """Restore exported English headers to the engine's canonical schema.

    This works regardless of the currently selected UI language, allowing an
    English export to be uploaded from the Portuguese interface and vice versa.
    """
    reverse_columns = {label: canonical for canonical, label in COLUMN_LABELS.items()}
    frame = dataframe.copy(deep=True).rename(columns=reverse_columns)
    return _transform_owned_columns(frame, reverse=True)


